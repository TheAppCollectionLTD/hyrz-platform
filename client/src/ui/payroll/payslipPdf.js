import { jsPDF } from 'jspdf';

const gbp = n => '£' + Number(n || 0).toFixed(2).replace(/\B(?=(\d{3})+(?!\d))/g, ',');
const ukDate = s => new Date(s + 'T00:00:00').toLocaleDateString('en-GB', { day: 'numeric', month: 'short', year: 'numeric' });
const BRAND = [15, 27, 45];

export function downloadPayslipPdf(p, worker = {}) {
  const doc = new jsPDF({ unit: 'mm', format: 'a4' });
  const W = 210, L = 18, R = W - 18;
  let y = 0;
  doc.setFillColor(...BRAND); doc.rect(0, 0, W, 30, 'F');
  doc.setTextColor(255); doc.setFont('helvetica', 'bold'); doc.setFontSize(24); doc.text('hyrz', L, 19);
  doc.setFontSize(13); doc.text('PAYSLIP', R, 14, { align: 'right' });
  doc.setFont('helvetica', 'normal'); doc.setFontSize(9); doc.text(`Tax year ${p.taxYear} · Week ${p.week}`, R, 20, { align: 'right' });

  doc.setTextColor(17); y = 44;
  const meta = [
    ['Employee', worker.name || '—'], ['Email', worker.email || '—'],
    ['Pay period', `${ukDate(p.start)} – ${ukDate(p.end)}`], ['Paid as', p.payType === 'paye' ? 'hyrz PAYE (employee)' : 'Independent contractor'],
    ...(p.payType === 'paye' ? [['Tax code', p.taxCode], ['NI category', p.niCategory]] : [])
  ];
  doc.setFontSize(10);
  meta.forEach(([k, v], i) => {
    const x = i % 2 ? 110 : L, row = y + Math.floor(i / 2) * 7;
    doc.setTextColor(120); doc.text(k, x, row); doc.setTextColor(17); doc.text(String(v), x + 26, row);
  });
  y += Math.ceil(meta.length / 2) * 7 + 6;

  const head = (title) => { doc.setFillColor(251, 248, 249); doc.rect(L, y - 5, R - L, 8, 'F'); doc.setFont('helvetica', 'bold'); doc.setFontSize(10); doc.text(title, L + 2, y); doc.text('Amount', R - 2, y, { align: 'right' }); doc.setFont('helvetica', 'normal'); y += 8; };
  const row = (label, amount, bold) => { doc.setFont('helvetica', bold ? 'bold' : 'normal'); doc.text(doc.splitTextToSize(label, 140)[0], L + 2, y); doc.text(amount, R - 2, y, { align: 'right' }); y += 6.5; };
  const rule = () => { doc.setDrawColor(230); doc.line(L, y - 4, R, y - 4); y += 2; };

  head('Earnings');
  p.lines.forEach(l => row(`${ukDate(l.date)}  ${l.shiftTitle} – ${l.businessName}`, gbp(l.gross)));
  rule(); row('Gross pay', gbp(p.gross), true); y += 4;

  if (p.payType === 'paye') {
    head('Deductions');
    row(`Income Tax (code ${p.taxCode})`, '-' + gbp(p.incomeTax));
    row(`National Insurance (category ${p.niCategory})`, '-' + gbp(p.employeeNi));
    rule(); row('Total deductions', '-' + gbp(p.incomeTax + p.employeeNi), true); y += 4;
  }

  doc.setFillColor(...BRAND); doc.rect(L, y - 2, R - L, 14, 'F');
  doc.setTextColor(255); doc.setFont('helvetica', 'bold'); doc.setFontSize(13);
  doc.text('Take-home pay', L + 4, y + 7); doc.text(gbp(p.net), R - 4, y + 7, { align: 'right' });
  y += 24;

  doc.setTextColor(110); doc.setFont('helvetica', 'normal'); doc.setFontSize(8.5);
  const note = p.payType === 'paye'
    ? `Employer National Insurance paid by hyrz on your behalf: ${gbp(p.employerNi)}. This does not reduce your pay. Tax and NI are worked out on a weekly (non-cumulative) basis.`
    : 'You were paid gross as a self-employed contractor. No tax or National Insurance has been deducted. Remember to declare this income through Self Assessment.';
  doc.text(doc.splitTextToSize(note, R - L), L, y);
  doc.text(`Generated by hyrz on ${new Date().toLocaleDateString('en-GB', { day: 'numeric', month: 'long', year: 'numeric' })}`, L, 285);

  doc.save(`hyrz-payslip-${p.taxYear.replace('/', '-')}-week-${p.week}.pdf`);
}
